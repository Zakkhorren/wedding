import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const production = process.argv.includes("--without-test-deletes");
const clean = (source) =>
  source.replace(/^\uFEFF/, "").replace(/^export (?!default)/gm, "");
let main = fs
  .readFileSync(path.join(root, "worker/wedding-rsvp-api.source.mjs"), "utf8")
  .replace(/^\uFEFF/, "")
  .replace(/^import\s[\s\S]*?;\r?\n/gm, "");
if (production)
  main = main
    .replace(/\/\* TEST_ADMIN_BEGIN \*\/[\s\S]*?\/\* TEST_ADMIN_END \*\//g, "")
    .replaceAll("TEST_ADMIN_HELP", "''");
const modules = [
  "rsvp-policy.mjs",
  "turnstile-verifier.mjs",
  ...(production ? [] : ["test-admin.mjs"]),
];
const result =
  "// GENERATED by node scripts/build-worker.mjs" +
  (production ? " --without-test-deletes" : "") +
  "\n// Self-contained ES module for manual Cloudflare upload. No secrets.\n" +
  modules
    .map((name) =>
      clean(fs.readFileSync(path.join(root, "worker", name), "utf8")),
    )
    .join("\n") +
  "\n" +
  main;
const output = production
  ? "wedding-rsvp-api.production.js"
  : "wedding-rsvp-api.js";
fs.writeFileSync(path.join(root, "worker", output), result.replace(/[ \t]+$/gm, ""));
console.log("Built worker/" + output);
